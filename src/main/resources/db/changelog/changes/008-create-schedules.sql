CREATE TABLE public.schedules
(
    id             BIGINT PRIMARY KEY
        GENERATED BY DEFAULT AS IDENTITY,
    study_group_id BIGINT NOT NULL REFERENCES public.study_groups (id),
    course_id      BIGINT NOT NULL REFERENCES public.courses (id),
    teacher_id     BIGINT NOT NULL REFERENCES public.teachers (id),
    starts_at      TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    ends_at        TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    created_at     TIMESTAMP WITHOUT TIME ZONE
    NOT NULL DEFAULT(CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    updated_at     TIMESTAMP WITHOUT TIME ZONE
    NOT NULL DEFAULT(CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    deleted_at     TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT chk_schedules_time CHECK (ends_at > starts_at)
);

